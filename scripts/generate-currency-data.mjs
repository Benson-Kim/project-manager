/**
 * Regenerates src/lib/currency/currency-data.generated.ts.
 *
 * Two tables no browser or Node API exposes:
 *   region -> currency   CLDR supplemental/currencyData.json (current legal tender only)
 *   time zone -> region  IANA tzdata zone.tab / zone1970.tab
 *
 * The currency *list* is not generated: it comes from Intl at runtime
 * (src/lib/currency/currencies.ts), so it follows the platform's ICU data.
 *
 * Usage: node scripts/generate-currency-data.mjs [path-to-currencyData.json]
 * Fetch the CLDR file with:
 *   curl -sSo /tmp/currencyData.json \
 *     https://cdn.jsdelivr.net/npm/cldr-core@46.0.0/supplemental/currencyData.json
 */
import { readFileSync, writeFileSync } from "node:fs";

const CLDR = process.argv[2] ?? new URL("./cldr-currencyData.json", import.meta.url).pathname;
const ZONE_TABS = ["/usr/share/zoneinfo/zone.tab", "/usr/share/zoneinfo/zone1970.tab"];
const OUT = new URL("../src/lib/currency/currency-data.generated.ts", import.meta.url).pathname;

const regionCurrency = () => {
  const { region } = JSON.parse(readFileSync(CLDR, "utf8")).supplemental.currencyData;
  const out = {};
  for (const [code, history] of Object.entries(region)) {
    if (!/^[A-Z]{2}$/.test(code)) continue;
    const live = history
      .flatMap((entry) => Object.entries(entry))
      .filter(([, v]) => v._to === undefined && v._tender !== "false")
      .map(([currency]) => currency);
    const currency = live.at(-1);
    if (currency && /^[A-Z]{3}$/.test(currency)) out[code] = currency;
  }
  return out;
};

const zoneRegion = () => {
  const out = {};
  for (const path of ZONE_TABS) {
    let text;
    try {
      text = readFileSync(path, "utf8");
    } catch {
      continue;
    }
    for (const line of text.split("\n")) {
      if (!line || line.startsWith("#")) continue;
      const [countries, , zone] = line.split("\t");
      const region = countries?.split(",")[0];
      if (zone && region && /^[A-Z]{2}$/.test(region) && !out[zone]) out[zone] = region;
    }
  }
  return out;
};

const literal = (map) =>
  Object.keys(map)
    .sort()
    .map((key) => `  ${/^[A-Z]{2}$/.test(key) ? key : JSON.stringify(key)}: "${map[key]}",`)
    .join("\n");

const regions = regionCurrency();
const zones = zoneRegion();
if (Object.keys(regions).length < 200) throw new Error("region->currency table looks truncated");
if (Object.keys(zones).length < 200) throw new Error("zone->region table looks truncated");

writeFileSync(
  OUT,
  `// Generated by scripts/generate-currency-data.mjs — do not edit by hand.
// Sources: CLDR supplemental/currencyData.json (region -> current legal tender)
// and IANA tzdata zone.tab (time zone -> primary region).
// The list of currencies is NOT here: Intl supplies it at runtime (./currencies).

/** A country/region's current currency, for suggesting one. ${Object.keys(regions).length} regions. */
export const REGION_CURRENCY: Readonly<Record<string, string>> = {
${literal(regions)}
};

/** An IANA time zone's primary region, so a user's zone suggests a currency. ${Object.keys(zones).length} zones. */
export const ZONE_REGION: Readonly<Record<string, string>> = {
${literal(zones)}
};
`,
);
console.log(`regions: ${Object.keys(regions).length}  zones: ${Object.keys(zones).length}`);
